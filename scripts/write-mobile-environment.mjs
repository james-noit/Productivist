// Writes src/environments/environment.mobile.ts (git-ignored) for `npm run build:mobile`.
// The Capacitor WebView is not served from the app's origin (https://localhost on Android, capacitor://localhost
// on iOS), so it needs an absolute API URL:
//   API_URL=https://<frontend-domain> npm run build:mobile
// (the frontend host proxies /api/* to the backend). Without API_URL the app is built with sync disabled.
import { writeFileSync } from 'node:fs';

const raw = (process.env.API_URL ?? '').trim().replace(/\/+$/, '');
if (raw && !/^https?:\/\//.test(raw)) {
  console.error(`API_URL must start with http:// or https:// (got "${raw}")`);
  process.exit(1);
}

writeFileSync(
  'src/environments/environment.mobile.ts',
  `// Generated by scripts/write-mobile-environment.mjs. Do not edit or commit.
export const environment = {
  syncEnabled: ${raw ? 'true' : 'false'},
  apiUrl: ${JSON.stringify(raw)},
};
`,
);
console.log(raw ? `Mobile build will sync with ${raw}` : 'API_URL not set: mobile build will have sync disabled');
