// Writes src/environments/environment.thunderbird.ts (git-ignored) for `npm run build:tb`.
// An add-on page is not served from the app's origin, so it needs an absolute API URL:
//   API_URL=https://<frontend-domain> npm run build:tb
// (the frontend host proxies /api/* to the backend). Without API_URL the add-on is built with sync disabled.
import { writeFileSync } from 'node:fs';

const raw = (process.env.API_URL ?? '').trim().replace(/\/+$/, '');
if (raw && !/^https?:\/\//.test(raw)) {
  console.error(`API_URL must start with http:// or https:// (got "${raw}")`);
  process.exit(1);
}

writeFileSync(
  'src/environments/environment.thunderbird.ts',
  `// Generated by scripts/write-thunderbird-environment.mjs. Do not edit or commit.
export const environment = {
  syncEnabled: ${raw ? 'true' : 'false'},
  apiUrl: ${JSON.stringify(raw)},
};
`,
);
console.log(raw ? `Thunderbird build will sync with ${raw}` : 'API_URL not set: Thunderbird build will have sync disabled');
