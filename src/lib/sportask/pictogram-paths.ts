import type { PictogramId } from './catalog/pictograms';

/**
 * The pictograms (PLAN section 9.3): a stick figure per movement family on a 64px grid, two key poses each (`a`, `b`), drawn as
 * strokes (never fills) so a skin can colour and glow them. Facing right; the ground is y = 58. First-pass drawings: phase 6
 * polishes them. The component alternates the poses with CSS; under reduced motion only `a` shows.
 */

type Pt = readonly [number, number];
interface Pose {
  head?: Pt;
  lines?: Pt[][];
  circles?: [number, number, number][];
  raw?: string[];
}

const HEAD_R = 3.6;
const n = (v: number): string => String(Math.round(v * 10) / 10);

function build(pose: Pose): string[] {
  const out: string[] = [];
  if (pose.head) {
    const [x, y] = pose.head;
    out.push(`M${n(x - HEAD_R)} ${n(y)}a${HEAD_R} ${HEAD_R} 0 1 0 ${2 * HEAD_R} 0a${HEAD_R} ${HEAD_R} 0 1 0 ${-2 * HEAD_R} 0`);
  }
  for (const line of pose.lines ?? []) out.push('M' + line.map(([x, y]) => `${n(x)} ${n(y)}`).join('L'));
  for (const [x, y, r] of pose.circles ?? []) out.push(`M${n(x - r)} ${n(y)}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`);
  out.push(...(pose.raw ?? []));
  return out;
}

